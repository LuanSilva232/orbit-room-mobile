const listeners = new Set<() => void>();
let activeLanguage: AppLanguage = 'pt-BR';

export function getAppLanguage(): AppLanguage {
  return activeLanguage;
}

export function setAppLanguage(language: AppLanguage): void {
  if (activeLanguage === language) return;
  activeLanguage = language;
  listeners.forEach((listener) => listener());
}

export function subscribeAppLanguage(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function useAppLanguage(): AppLanguage {
  return useSyncExternalStore(
    subscribeAppLanguage,
    getAppLanguage,
    getAppLanguage
  );
}

export function translateText(text: string, language = activeLanguage): string {
  if (language === 'pt-BR') return text;
  const translation = translations[text];
  if (translation) return translation[LANGUAGE_INDEX[language] - 1];
  const index = LANGUAGE_INDEX[language] - 1;
  const roomAction = text.match(/^Sala "(.+)" (criada|atualizada|excluída)\.$/);
  if (roomAction) {
    const actions: Record<string, [string, string, string]> = {
      criada: ['created', 'creada', 'créé'],
      atualizada: ['updated', 'actualizada', 'mis à jour'],
      excluída: ['deleted', 'eliminada', 'supprimé'],
    };
    return `${language === 'en' ? 'Room' : language === 'es' ? 'Sala' : 'Salon'} "${roomAction[1]}" ${actions[roomAction[2]][index]}.`;
  }
  const inviteSent = text.match(/^Convite enviado para (.+)\.$/);
  if (inviteSent) {
    const lead = ['Invitation sent to', 'Invitación enviada a', 'Invitation envoyée à'][index];
    return `${lead} ${inviteSent[1]}.`;
  }
  const volume = text.match(/^Volume das vozes definido em (\d+)%\.$/);
  if (volume) {
    const lead = ['Voice volume set to', 'Volumen de voz ajustado al', 'Volume des voix réglé à'][index];
    return `${lead} ${volume[1]}%.`;
  }
  const count = text.match(/^(\d+) (ativas|pendentes|aguardando|amigos)$/);
  if (count) {
    const labels: Record<string, [string, string, string]> = {
      ativas: ['active', 'activas', 'actives'],
      pendentes: ['pending', 'pendientes', 'en attente'],
      aguardando: ['waiting', 'pendientes', 'en attente'],
      amigos: ['friends', 'amigos', 'amis'],
    };
    return `${count[1]} ${labels[count[2]][index]}`;
  }
  return text;
}

export function isAppLanguage(value: unknown): value is AppLanguage {
  return value === 'pt-BR' || value === 'en' || value === 'es' || value === 'fr';
}
